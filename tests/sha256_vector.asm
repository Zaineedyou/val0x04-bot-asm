BITS 64
DEFAULT REL

extern sha256_digest
extern hmac_sha256
extern hkdf_expand_sha256
global _start

%define SYS_EXIT 60

section .text
_start:
    lea rdi, [empty_message]
    xor esi, esi
    lea rdx, [empty_digest]
    call check_digest
    test eax, eax
    jnz .fail

    lea rdi, [abc_message]
    mov esi, abc_message_len
    lea rdx, [abc_digest]
    call check_digest
    test eax, eax
    jnz .fail

    lea rdi, [boundary_message]
    mov esi, boundary_message_len
    lea rdx, [boundary_digest]
    call check_digest
    test eax, eax
    jnz .fail

    lea rdi, [hmac_key]
    mov esi, hmac_key_len
    lea rdx, [hmac_message]
    mov ecx, hmac_message_len
    lea r8, [hmac_digest]
    call hmac_sha256
    test eax, eax
    jnz .fail
    lea rdi, [hmac_digest]
    lea rsi, [hmac_expected]
    mov edx, 32
    call check_bytes
    test eax, eax
    jnz .fail

    ; RFC 5869 test case 1: Extract then Expand to 42 bytes.
    lea rdi, [hkdf_salt]
    mov esi, hkdf_salt_len
    lea rdx, [hkdf_ikm]
    mov ecx, hkdf_ikm_len
    lea r8, [hkdf_prk]
    call hmac_sha256
    test eax, eax
    jnz .fail
    lea rdi, [hkdf_prk]
    lea rsi, [hkdf_prk_expected]
    mov edx, 32
    call check_bytes
    test eax, eax
    jnz .fail

    lea rdi, [hkdf_prk]
    mov esi, 32
    lea rdx, [hkdf_info]
    mov ecx, hkdf_info_len
    lea r8, [hkdf_okm]
    mov r9d, 42
    call hkdf_expand_sha256
    test eax, eax
    jnz .fail
    lea rdi, [hkdf_okm]
    lea rsi, [hkdf_okm_expected]
    mov edx, 42
    call check_bytes
    test eax, eax
    jnz .fail

    mov eax, SYS_EXIT
    xor edi, edi
    syscall
.fail:
    mov eax, SYS_EXIT
    mov edi, 1
    syscall

; rdi=message, esi=length, rdx=expected digest. EAX=0 when equal.
; rdi=actual bytes, rsi=expected bytes, edx=length. EAX=0 when equal.
check_bytes:
    xor ecx, ecx
.loop:
    cmp ecx, edx
    jae .pass
    mov al, [rdi + rcx]
    cmp al, [rsi + rcx]
    jne .mismatch
    inc ecx
    jmp .loop
.pass:
    xor eax, eax
    ret
.mismatch:
    mov eax, 1
    ret

check_digest:
    push r12
    mov r12, rdx
    lea rdx, [digest]
    call sha256_digest
    xor ecx, ecx
.compare:
    cmp ecx, 32
    jae .pass
    mov al, [digest + rcx]
    cmp al, [r12 + rcx]
    jne .mismatch
    inc ecx
    jmp .compare
.pass:
    xor eax, eax
    jmp .out
.mismatch:
    mov eax, 1
.out:
    pop r12
    ret

